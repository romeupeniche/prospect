export function normalizePositionLanguage(language?: string | null): PositionLanguage {
  const normalized = (language ?? DEFAULT_POSITION_LANGUAGE).toLowerCase();
  if (normalized.startsWith("pt") || normalized.startsWith("br")) return "pt";
  if (normalized.startsWith("es")) return "es";
  if (normalized.startsWith("en")) return "en";
  return DEFAULT_POSITION_LANGUAGE;
}

function normalizePositionCode(position?: string | null): string {
  return (position ?? "").trim().toUpperCase();
}

export function formatPosition(position?: string | null, language?: string | null): string {
  const code = normalizePositionCode(position);
  if (!code) return "";
  const lang = normalizePositionLanguage(language);
  return POSITION_ABBREVIATIONS[lang][code] ?? code;
}

export function formatPositionName(position?: string | null, language?: string | null): string {
  const code = normalizePositionCode(position);
  if (!code) return "";
  const lang = normalizePositionLanguage(language);
  const baseCode = SLOT_TO_BASE_POSITION[code] ?? code;
  return POSITION_NAMES[lang][baseCode] ?? formatPosition(code, lang);
}

export function getPositionLanguageFromSave(saveData?: Pick<SaveData, "language"> | null): PositionLanguage {
  return normalizePositionLanguage(saveData?.language);
}
